def get_table_data(n):
    """Returns list of dicts for table rows from 1 to 10."""
    rows = []
    # Spoken forms like "Two ones are two", "Two twos are four"
    words_map = {
        1: "ones are", 2: "twos are", 3: "threes are", 4: "fours are",
        5: "fives are", 6: "sixes are", 7: "sevens are", 8: "eights are",
        9: "nines are", 10: "tens are"
    }
    for i in range(1, 11):
        prod = n * i
        w = words_map.get(i, "times")
        spoken = f"{n} {w} {prod}"
        rows.append({
            "table": n,
            "multiplier": i,
            "product": prod,
            "display": f"{n} × {i} = {prod}",
            "spoken": spoken
        })
    return rows


